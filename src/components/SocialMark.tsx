/** The lucide icons that do exist, for the non-brand links. */
const LUCIDE: Record<string, typeof Globe> = {
  whatsapp: MessageCircle,
  email: Mail,
  website: Globe,
};

export default function SocialMark({
  network,
  className = "w-4 h-4",
}: {
  network?: string;
  className?: string;
}) {
  const key = String(network || "").toLowerCase();

  const Lucide = LUCIDE[key];
  if (Lucide) return <Lucide className={className} />;

  const path = PATHS[key];
  if (!path) return <Globe className={className} />;

  return (
    <svg className={className} fill="currentColor" viewBox="0 0 24 24" aria-hidden="true">
      <path d={path} />
    </svg>
  );
}

